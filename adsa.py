def login(username: str, password: str) -> Optional[Dict]:
    """Returns the user on success, None on wrong details.
    Raises PermissionError while the account is locked."""
    data = load_data()
    u = data["users"].get(username)
    if u is None:
        _audit(data, "LOGIN_FAILED", username, reason="unknown username")
        save_data(data)
        return None
    if u["locked_until"]:
        until = datetime.fromisoformat(u["locked_until"])
        if until > datetime.now(timezone.utc):
            raise PermissionError(f"Account locked after {MAX_FAILED_LOGINS} wrong passwords. "
                                  f"Try again after {_short_time(u['locked_until'])}.")
    _, actual = _hash_password(password, bytes.fromhex(u["salt"]))
    if not hmac.compare_digest(actual, u["password_hash"]):  #constant-time comparison
        u["failed_attempts"] += 1
        if u["failed_attempts"] >= MAX_FAILED_LOGINS:
            u["failed_attempts"] = 0
            u["locked_until"] = (datetime.now(timezone.utc) + timedelta(minutes=LOCK_MINUTES)).isoformat()
            _audit(data, "ACCOUNT_LOCKED", username)
            admin = _admin_name(data)
            if admin != username:
                _send(data, admin, f"SECURITY: account '{username}' was locked after "
                                   f"{MAX_FAILED_LOGINS} wrong passwords.")
        else:
            _audit(data, "LOGIN_FAILED", username, reason="wrong password")
        save_data(data)
        return None
    u["failed_attempts"] = 0
    u["locked_until"] = None
    if u["status"] == "PENDING":
        save_data(data)
        raise PermissionError("Your account is waiting for administrator approval.")
    if u["status"] == "REJECTED":
        save_data(data)
        raise PermissionError("Your account request was rejected by the administrator.")
    _audit(data, "LOGIN", username)
    save_data(data)
    return {"username": username, "role": u["role"]}

def logout(user: Dict):
    data = load_data()
    _audit(data, "LOGOUT", user["username"])
    save_data(data)

# STEP 4: SHA-256 HASHING PRIMITIVES
def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()  #SHA-256 produces a 256-bit digest, represented by 64 hexadecimal characters.

def sha256_text(text: str) -> str:
    return sha256_bytes(text.encode("utf-8"))#This first converts a string into UTF-8 bytes, then calculates its SHA-256 hash.

def hash_leaf(data: bytes) -> str: #This is called domain separation. It distinguishes a leaf hash from an internal-node hash.
    return sha256_bytes(b"\x00" + data)

def hash_pair(left: str, right: str) -> str:
    """Combine two child hashes into one parent hash."""
    return sha256_bytes(b"\x01" + bytes.fromhex(left) + bytes.fromhex(right))

# STEP 2: EVIDENCE PREPROCESSING (file reading + Shannon entropy)
def read_file_bytes(file_path: str) -> bytes:
    if not os.path.isfile(file_path):
        raise FileNotFoundError(f"File not found: {file_path}")
    with open(file_path, "rb") as f:  #rb = read binary, works for any file type
        return f.read()

#H = −Σ p(x) · log₂(p(x))   (0 = all bytes same, 8 = completely random)
def calculate_entropy(data: bytes) -> float:
    if not data:
        return 0.0
    frequency = Counter(data)   #frequency table: byte value -> how many times it appears
    n = len(data)
    entropy = 0.0
    for count in frequency.values():
        p = count / n
        entropy -= p * math.log2(p)
    return entropy

# STEP 3: ADAPTIVE EVIDENCE CHUNKING
#   entropy >= 6.5 -> 4 KB   |   >= 4.5 -> 16 KB   |   otherwise -> 32 KB
LOW_ENTROPY  = 4.5
HIGH_ENTROPY = 6.5
SMALL_CHUNK  = 4  * 1024
MEDIUM_CHUNK = 16 * 1024
LARGE_CHUNK  = 32 * 1024

def choose_chunk_size(entropy: float) -> int:
    if entropy >= HIGH_ENTROPY:
        return SMALL_CHUNK
    if entropy >= LOW_ENTROPY:
        return MEDIUM_CHUNK
    return LARGE_CHUNK

def adaptive_chunk_file(file_data: bytes) -> Tuple[List[bytes], List[Dict]]:
    chunks, info = [], []
    region_start, region_index = 0, 0
    while region_start < len(file_data):
        region_end = min(region_start + LARGE_CHUNK, len(file_data))
        region = file_data[region_start:region_end]
        entropy = calculate_entropy(region)
        chunk_size = choose_chunk_size(entropy)
        local = 0
        while local < len(region):
            end_local = min(local + chunk_size, len(region))
            chunks.append(region[local:end_local])
            info.append({
                "chunk_index":         len(chunks) - 1,
                "anchor_region":       region_index,
                "start_byte":          region_start + local,
                "end_byte":            region_start + end_local - 1,
                "size_bytes":          end_local - local,
                "entropy":             round(entropy, 6),
                "selected_chunk_size": chunk_size
            })
            local = end_local
        region_start = region_end
        region_index += 1
    return chunks, info

# STEP 5: MULTI-LAYER MERKLE CONSTRUCTION
def build_merkle_tree(leaf_hashes: List[str]) -> Dict:
    if not leaf_hashes:
        raise ValueError("Cannot build a Merkle Tree with no leaves.")
    levels = [leaf_hashes.copy()]  #every level is stored (needed for proofs in step 9)
    while len(levels[-1]) > 1:     #bottom-up until one root remains
        current, next_level = levels[-1], []
        for i in range(0, len(current), 2):
            if i + 1 < len(current):
                next_level.append(hash_pair(current[i], current[i + 1]))
            else:
                next_level.append(current[i])  #odd node promoted
        levels.append(next_level)
    return {"leaf_count": len(leaf_hashes), "height": len(levels) - 1,
            "levels": levels, "root": levels[-1][0]}

def build_content_tree(chunks: List[bytes], chunk_info: List[Dict]) -> Dict:
    if not chunks:
        raise ValueError("Evidence file is empty.")
    leaf_hashes = [hash_leaf(c) for c in chunks]  #STEP 4: one SHA-256 per chunk = leaf
    tree = build_merkle_tree(leaf_hashes)
    enriched = []
    for i, h in enumerate(leaf_hashes):
        item = chunk_info[i].copy()
        item["leaf_hash"] = h
        enriched.append(item)
    return {"chunk_count": len(chunks), "chunks": enriched, "merkle_tree": tree, "root": tree["root"]}

def build_metadata_tree(metadata: Dict) -> Dict:
    records, hashes = [], []
    for key, value in sorted(metadata.items()):  #sorted so the order is always the same
        fh = hash_leaf(f"{key}={json.dumps(value)}".encode("utf-8"))
        hashes.append(fh)
        records.append({"field": key, "value": value, "leaf_hash": fh})
    tree = build_merkle_tree(hashes)
    return {"fields": records, "merkle_tree": tree, "root": tree["root"]}

def fingerprint_file(file_path: str) -> Dict:
    """Steps 2-5: read -> metadata + entropy -> chunks -> SHA-256 -> both trees -> evidence root."""
    return fingerprint_bytes(read_file_bytes(file_path), os.path.basename(file_path))

def fingerprint_bytes(file_data: bytes, file_name: str) -> Dict:
    metadata = {
        "file_name":       file_name,
        "file_type":       os.path.splitext(file_name)[1].lower() or "unknown",
        "file_size_bytes": len(file_data)
    }
    chunks, chunk_info = adaptive_chunk_file(file_data)
    content_tree  = build_content_tree(chunks, chunk_info)
    metadata_tree = build_metadata_tree(metadata)
    evidence_root = hash_pair(metadata_tree["root"], content_tree["root"])
    return {
        "metadata":      metadata,
        "metadata_tree": metadata_tree,
        "content_tree":  content_tree,
        "roots": {
            "metadata_root": metadata_tree["root"],
            "content_root":  content_tree["root"],
            "evidence_root": evidence_root
        }
    }

