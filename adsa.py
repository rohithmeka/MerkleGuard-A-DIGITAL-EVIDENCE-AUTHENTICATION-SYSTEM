def verify_report(user: Dict, path: str) -> Dict:
    if not is_admin(user):
        raise PermissionError("Only the administrator can verify reports.")
    if not os.path.isfile(path):
        raise FileNotFoundError(f"File not found: {path}")
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    cut = text.rfind("\n" + REPORT_SIGNATURE)
    if cut == -1:
        return {"genuine": False, "reason": "This is not a MerkleGuard report (no signature found)."}
    body = text[:cut]
    given = text[cut + 1 + len(REPORT_SIGNATURE):].strip()
    expected = hmac.new(_get_key(), body.encode("utf-8"), hashlib.sha256).hexdigest()
    if hmac.compare_digest(given, expected):
        return {"genuine": True, "reason": "Signature valid - the report is exactly as MerkleGuard produced it."}
    return {"genuine": False, "reason": "Signature does NOT match - the report has been modified."}

# ============================================================
# BENCHMARK: FIXED-SIZE vs ADAPTIVE CHUNKING (research validation)
# Same file, four strategies. For each one we measure:
#   chunks + tree height  -> storage and proof size
#   build time            -> chunk + hash + Merkle tree (best of 3 runs)
#   localization          -> 1-byte edits at fixed random positions; how many
#                            bytes does the Merkle comparison flag as affected?
# Smaller affected size = more precise; fewer chunks = less overhead.
# ============================================================

def _fixed_chunks(data: bytes, size: int) -> List[Tuple[int, int, bytes]]:
    return [(i, min(i + size, len(data)) - 1, data[i:i + size]) for i in range(0, len(data), size)]

def _adaptive_chunks(data: bytes) -> List[Tuple[int, int, bytes]]:
    chunks, info = adaptive_chunk_file(data)
    return [(c["start_byte"], c["end_byte"], chunks[i]) for i, c in enumerate(info)]

def _affected_bytes(orig: List[Tuple[int, int, str]], new: List[Tuple[int, int, str]]) -> int:
    """Bytes flagged as changed when the two chunk lists are compared."""
    orig_set, new_set = set(orig), set(new)
    ranges = [(s, e) for s, e, h in orig if (s, e, h) not in new_set]
    ranges += [(s, e) for s, e, h in new if (s, e, h) not in orig_set]
    return sum(e - s + 1 for s, e in _merge_ranges(ranges))

def _bench_data(data: bytes, name: str, edits: int) -> Dict:
    strategies = [("Fixed 4 KB",  lambda d: _fixed_chunks(d, SMALL_CHUNK)),
                  ("Fixed 16 KB", lambda d: _fixed_chunks(d, MEDIUM_CHUNK)),
                  ("Fixed 32 KB", lambda d: _fixed_chunks(d, LARGE_CHUNK)),
                  ("Adaptive",    _adaptive_chunks)]
    rng = random.Random(42)                                 #fixed seed -> same edits every run
    positions = [rng.randrange(len(data)) for _ in range(edits)]
    rows = []
    for sname, chunker in strategies:
        best = {"chunk": None, "hash": None, "tree": None}
        for _ in range(3):                                   #best of 3 runs for each stage
            t0 = time.perf_counter(); chunks = chunker(data)
            t1 = time.perf_counter(); leaves = [hash_leaf(c) for _, _, c in chunks]
            t2 = time.perf_counter(); tree = build_merkle_tree(leaves)
            t3 = time.perf_counter()
            for k, v in (("chunk", t1 - t0), ("hash", t2 - t1), ("tree", t3 - t2)):
                best[k] = v if best[k] is None else min(best[k], v)
        orig = [(s_, e_, leaves[i]) for i, (s_, e_, _) in enumerate(chunks)]
        affected = []
        for pos in positions:
            edited = bytearray(data)
            edited[pos] ^= 0xFF                              #change exactly one byte
            new = [(s_, e_, hash_leaf(c)) for s_, e_, c in chunker(bytes(edited))]
            affected.append(_affected_bytes(orig, new))
        rows.append({"strategy": sname, "chunks": len(chunks), "height": tree["height"],
                     "chunk_ms": best["chunk"] * 1000, "hash_ms": best["hash"] * 1000,
                     "tree_ms": best["tree"] * 1000, "stored_hash_kb": len(chunks) * 64 / 1024,
                     "avg_affected": sum(affected) / len(affected), "max_affected": max(affected)})
    return {"file": name, "size": len(data), "edits": edits, "entropy": calculate_entropy(data), "rows": rows}

