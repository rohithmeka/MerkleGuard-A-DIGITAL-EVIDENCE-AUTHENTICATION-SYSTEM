def load_original(record: Dict) -> Tuple[Optional[bytes], str]:
    """Returns (original bytes, 'verified') or (None, reason)."""
    path = _vault_path(record["evidence_id"])
    if not os.path.isfile(path):
        return None, "original copy missing from the vault"
    with open(path, "rb") as f:
        data = f.read()
    if len(data) != record["metadata"]["file_size_bytes"]:
        return None, "vault copy has been MODIFIED (size differs) - not trusted"
    chunks, info = adaptive_chunk_file(data)
    if build_content_tree(chunks, info)["root"] != record["roots"]["content_root"]:
        return None, "vault copy has been MODIFIED (Merkle root differs) - not trusted"
    return data, "verified"

def show_bytes(b: bytes, limit: int = 48) -> str:
    """Readable view of raw bytes: text if printable, otherwise hex."""
    if not b:
        return "(nothing)"
    part = b[:limit]
    if all(32 <= x < 127 or x in (9, 10, 13) for x in part):
        text = repr(part.decode("ascii"))
    else:
        part = b[:limit // 2]
        text = "hex " + part.hex(" ")
    return text + (" ..." if len(b) > len(part) else "")

def _common_prefix(a: bytes, b: bytes) -> int: #consecutive bytes
    lo, hi = 0, min(len(a), len(b))
    while lo < hi:                                   #binary search
        mid = (lo + hi + 1) // 2
        if a[:mid] == b[:mid]:
            lo = mid
        else:
            hi = mid - 1
    return lo

def _common_suffix(a: bytes, b: bytes, limit: int) -> int: #ends of both files
    lo, hi = 0, limit
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if a[len(a) - mid:] == b[len(b) - mid:]:
            lo = mid
        else:
            hi = mid - 1
    return lo

def _window(data: bytes, start: int, length: int) -> str:
    """The changed bytes with 12 bytes of context on each side."""
    return show_bytes(data[max(0, start - 12): start + length + 12], limit=64)

def _make_edit(op: str, original: bytes, current: bytes, o_off: int, o_len: int, c_off: int, c_len: int) -> Dict:
    return {"op": op, "offset": o_off, "orig_len": o_len, "cur_offset": c_off, "cur_len": c_len,
            "original": _window(original, o_off, o_len), "current": _window(current, c_off, c_len)}

def describe_edit(e: Dict) -> str:
    if e["op"] == "INSERTED":
        return f"{e['cur_len']} byte(s) INSERTED at byte {e['offset']}"
    if e["op"] == "DELETED":
        return f"{e['orig_len']} byte(s) DELETED at byte {e['offset']}"
    if e["orig_len"] == e["cur_len"]:
        return f"{e['orig_len']} byte(s) REPLACED at byte {e['offset']}"
    return f"{e['orig_len']} byte(s) REPLACED by {e['cur_len']} byte(s) at byte {e['offset']}"

ALIGN_LIMIT = 20000   #largest changed region aligned byte-by-byte with difflib

def find_edits(original: bytes, current: bytes, flagged: List[Tuple[int, int]]) -> List[Dict]:
    """Exact edits between the vault original and the submitted file.
    Same length -> compare position by position, only inside the chunks the Merkle tree flagged.
    Different length -> bytes were inserted/deleted, so positions shift: strip the common
    beginning and end, then align the changed middle (difflib) to separate real changes from shifts."""
    edits = []
    if len(original) == len(current):
        for s_, e_ in flagged:
            o, c = original[s_:e_ + 1], current[s_:e_ + 1]
            runs = _merge_ranges([(s_ + i, s_ + i) for i in range(len(o)) if o[i] != c[i]])
            for r0, r1 in runs:
                edits.append(_make_edit("REPLACED", original, current, r0, r1 - r0 + 1, r0, r1 - r0 + 1))
        return edits
    p = _common_prefix(original, current)
    sfx = _common_suffix(original, current, min(len(original), len(current)) - p)
    o_mid, c_mid = original[p:len(original) - sfx], current[p:len(current) - sfx]
    if len(o_mid) + len(c_mid) <= ALIGN_LIMIT:
        matcher = difflib.SequenceMatcher(None, o_mid, c_mid, autojunk=False)
        for tag, i1, i2, j1, j2 in matcher.get_opcodes():
            if tag == "equal":
                continue
            op = {"replace": "REPLACED", "insert": "INSERTED", "delete": "DELETED"}[tag]
            edits.append(_make_edit(op, original, current, p + i1, i2 - i1, p + j1, j2 - j1))
    else:
        # very large changed region: report it as one block instead of guessing
        op = "INSERTED" if not o_mid else "DELETED" if not c_mid else "REPLACED"
        edits.append(_make_edit(op, original, current, p, len(o_mid), p, len(c_mid)))
    return edits

# STEP 9: MERKLE-PROOF TAMPER LOCALIZATION

def generate_proof(levels: List[List[str]], index: int) -> List[Dict]:
    if not 0 <= index < len(levels[0]):
        raise ValueError(f"Chunk index must be between 0 and {len(levels[0]) - 1}.")
    proof = []
    for level in levels[:-1]:
        sibling = index ^ 1                      #even index -> right sibling, odd -> left sibling
        if sibling < len(level):                 #no sibling = node was promoted, nothing to add
            proof.append({"side": "left" if sibling < index else "right", "hash": level[sibling]})
        index //= 2
    return proof

def verify_proof(leaf_hash: str, proof: List[Dict], root: str) -> bool:
    current = leaf_hash
    for step in proof:
        if step["side"] == "left":
            current = hash_pair(step["hash"], current)
        else:
            current = hash_pair(current, step["hash"])
    return hmac.compare_digest(current, root)

def _merge_ranges(ranges: List[Tuple[int, int]]) -> List[Tuple[int, int]]:
    merged = []
    for start, end in sorted(ranges):
        if merged and start <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end))
        else:
            merged.append((start, end))
    return merged

def localize_tampering(record: Dict, current_fp: Dict, current_data: bytes) -> Dict:
    # --- metadata layer: which field changed ---
    old_fields = {f["field"]: f for f in record["metadata_tree"]["fields"]}
    new_fields = {f["field"]: f for f in current_fp["metadata_tree"]["fields"]}
    changed_fields = []
    for name in sorted(set(old_fields) | set(new_fields)):
        old, new = old_fields.get(name), new_fields.get(name)
        if old is None or new is None or old["leaf_hash"] != new["leaf_hash"]:
            changed_fields.append({"field": name,
                                   "original": old["value"] if old else None,
                                   "current":  new["value"] if new else None})

    # --- content layer: which chunk changed ---
    orig_chunks = record["content_tree"]["chunks"]
    cur_chunks  = current_fp["content_tree"]["chunks"]
    orig_levels = record["content_tree"]["merkle_tree"]["levels"]
    orig_root   = record["roots"]["content_root"]
    cur_by_range = {(c["start_byte"], c["end_byte"]): c for c in cur_chunks}
    same_layout = ([(c["start_byte"], c["end_byte"]) for c in orig_chunks] ==
                   [(c["start_byte"], c["end_byte"]) for c in cur_chunks])

    bad, compared = [], 0
    if same_layout:
        # same tree shape -> walk both trees from the root and only go down
        # into subtrees whose hashes differ: O(k log n) for k changed chunks
        method = "top-down Merkle tree comparison"
        cur_levels = current_fp["content_tree"]["merkle_tree"]["levels"]
        stack = [(len(orig_levels) - 1, 0)]
        while stack:
            lvl, j = stack.pop()
            compared += 1
            if orig_levels[lvl][j] == cur_levels[lvl][j]:
                continue                                  #whole subtree identical -> skip it
            if lvl == 0:
                bad.append(j)
                continue
            for child in (2 * j, 2 * j + 1):
                if child < len(orig_levels[lvl - 1]):
                    stack.append((lvl - 1, child))
        bad.sort()
    else:
        # chunk layout changed (size or entropy changed) -> check every original
        # chunk position on its own with its Merkle proof against the original root
        method = "per-chunk Merkle proof verification (chunk layout changed)"
        for c in orig_chunks:
            cc = cur_by_range.get((c["start_byte"], c["end_byte"]))
            if cc is None:
                bad.append(c["chunk_index"])
                continue
            proof = generate_proof(orig_levels, c["chunk_index"])
            compared += len(proof) + 1
            if not verify_proof(cc["leaf_hash"], proof, orig_root):
                bad.append(c["chunk_index"])

    changed_chunks, byte_ranges = [], []
    for i in bad:
        c = orig_chunks[i]
        cc = cur_by_range.get((c["start_byte"], c["end_byte"]))
        proof = generate_proof(orig_levels, i)
        if cc is None:
            state = "MISSING / RE-CHUNKED"
        else:
            # confirm with the Merkle proof: current chunk must NOT reach the original root
            state = "MODIFIED" if not verify_proof(cc["leaf_hash"], proof, orig_root) else "INTACT"
        if state != "INTACT":
            changed_chunks.append({"chunk_index": i, "start_byte": c["start_byte"],
                                   "end_byte": c["end_byte"], "state": state,
                                   "proof_length": len(proof)})
            byte_ranges.append((c["start_byte"], c["end_byte"]))
    orig_ranges = {(c["start_byte"], c["end_byte"]) for c in orig_chunks}
    added = [(c["start_byte"], c["end_byte"]) for c in cur_chunks
             if (c["start_byte"], c["end_byte"]) not in orig_ranges]
    byte_ranges.extend(added)
    affected = _merge_ranges(byte_ranges)

    # --- exact edits: compare with the verified vault copy ---
    original, vault = load_original(record)
    edits = []
    if original is not None and affected:
        edits = find_edits(original, current_data, affected)
        for e in edits:
            last = e["offset"] + max(e["orig_len"], 1) - 1
            e["chunks"] = [c["chunk_index"] for c in orig_chunks
                           if c["start_byte"] <= last and c["end_byte"] >= e["offset"]]

    return {
        "edits":            edits,
        "vault":            vault,
        "changed_fields":   changed_fields,
        "changed_chunks":   changed_chunks,
        "added_ranges":     added,
        "affected_ranges":   _merge_ranges(byte_ranges),
        "method":           method,
        "hashes_compared":  compared,
        "total_chunks":     len(orig_chunks),
        "tree_height":      len(orig_levels) - 1,
        "original_size":    record["metadata"]["file_size_bytes"],
        "current_size":     current_fp["metadata"]["file_size_bytes"]
    }

def _ranges_text(ranges) -> str:
    return ", ".join(f"{s}-{e}" for s, e in ranges) if ranges else "none"

def _loc_summary(loc: Optional[Dict]) -> Optional[Dict]:
    """Short version of the localization that is saved in the chain of custody."""
    if not loc:
        return None
    return {
        "changed_fields": [f"{f['field']}: {f['original']} -> {f['current']}" for f in loc["changed_fields"]],
        "changed_chunks": [c["chunk_index"] for c in loc["changed_chunks"]],
        "affected_ranges": _ranges_text(loc["affected_ranges"]),
        "exact_changes":  ("; ".join(describe_edit(e) for e in loc["edits"][:5])
                           + (f"; ... {len(loc['edits']) - 5} more" if len(loc["edits"]) > 5 else "")
                           if loc["edits"] else
                           ("none in content" if not loc["affected_ranges"] else f"unavailable: {loc['vault']}")),
        "example":        [f"{describe_edit(e)}: original {e['original']} -> now {e['current']}"
                           for e in loc["edits"][:3]],
        "size":           f"{loc['original_size']} -> {loc['current_size']} bytes"
    }

def verify_single_chunk(user: Dict, evidence_id: str, chunk_index: int, file_path: str = "") -> Dict:
    """Prove ONE chunk against the stored content root using only log2(n) hashes.
    With a file path, that chunk of the given file is checked; without, the stored leaf."""
    record = _get_record(load_data(), evidence_id)
    if not can_view(user, record):
        raise PermissionError("You are not allowed to access this evidence.")
    chunks = record["content_tree"]["chunks"]
    levels = record["content_tree"]["merkle_tree"]["levels"]
    proof = generate_proof(levels, chunk_index)
    c = chunks[chunk_index]
    if file_path:
        data = read_file_bytes(file_path)
        piece = data[c["start_byte"]:c["end_byte"] + 1]
        leaf = hash_leaf(piece)
        source = f"bytes {c['start_byte']}-{c['end_byte']} of {os.path.basename(file_path)}"
        content = show_bytes(piece)
    else:
        # no file given -> check the vault copy's chunk: hash its REAL bytes (not the stored hash)
        path_v = _vault_path(record["evidence_id"])
        if not os.path.isfile(path_v):
            raise ValueError("The original copy is missing from the vault - nothing to check.")
        with open(path_v, "rb") as f:
            data = f.read()
        piece = data[c["start_byte"]:c["end_byte"] + 1]
        leaf = hash_leaf(piece)
        source = f"bytes {c['start_byte']}-{c['end_byte']} of the vault copy"
        content = show_bytes(piece)
    path, current = [], leaf
    for step in proof:
        current = hash_pair(step["hash"], current) if step["side"] == "left" else hash_pair(current, step["hash"])
        path.append({**step, "result": current})
    return {"chunk": c, "source": source, "content": content, "leaf_hash": leaf, "proof": path,
            "root": record["roots"]["content_root"],
            "valid": verify_proof(leaf, proof, record["roots"]["content_root"])}

# STEP 7 + 8: RE-VERIFICATION AND LAYER-WISE TAMPER DETECTION
def compare_with_original(file_path: str, record: Dict) -> Dict:
    current_data = read_file_bytes(file_path)
    current_fp = fingerprint_bytes(current_data, os.path.basename(file_path))
    current = current_fp["roots"]
    stored  = record["roots"]
    metadata_match = hmac.compare_digest(stored["metadata_root"], current["metadata_root"])
    content_match  = hmac.compare_digest(stored["content_root"],  current["content_root"])
    if metadata_match and content_match:
        status = "AUTHENTIC"
    elif content_match:
        status = "METADATA TAMPERED"
    elif metadata_match:
        status = "CONTENT TAMPERED"
    else:
        status = "BOTH TAMPERED"
    return {
        "status": status,
        "metadata_match": metadata_match,
        "content_match": content_match,
        "evidence_match": stored["evidence_root"] == current["evidence_root"],
        "stored": stored,
        "current": current,
        "localization": localize_tampering(record, current_fp, current_data) if status != "AUTHENTIC" else None
    }

# STEP 1 (PART B) + CHAIN OF CUSTODY
def _log(record: Dict, event: str, by: str, **details):
    record["custody_log"].append({"event": event, "by": by, "time": _now(), **details})

def _get_record(data: Dict, evidence_id: str) -> Dict:
    if evidence_id not in data["evidence"]:
        raise ValueError(f"Evidence ID not found: {evidence_id}")
    return data["evidence"][evidence_id]

def _summary(record: Dict, check: Dict, who: str) -> str:
    text = (f"{record['evidence_id']} ({record['metadata']['file_name']}) checked by {who}: "
            f"{check['status']} | Metadata root: {'MATCH' if check['metadata_match'] else 'MISMATCH'}"
            f" | Content root: {'MATCH' if check['content_match'] else 'MISMATCH'}")
    loc = check.get("localization")
    if loc:
        if loc["changed_fields"]:
            text += " | Changed fields: " + ", ".join(f["field"] for f in loc["changed_fields"])
        if loc["affected_ranges"]:
            text += " | Affected chunk ranges: " + _ranges_text(loc["affected_ranges"])
        if loc["edits"]:
            e = loc["edits"][0]
            text += (f" | Exact change: {describe_edit(e)}, original {e['original']} -> now {e['current']}"
                     + (f" (+{len(loc['edits']) - 1} more)" if len(loc["edits"]) > 1 else ""))
    return text

def open_case(record: Dict) -> Optional[Dict]:
    for case in record["tamper_cases"]:
        if case["state"] == "PENDING":
            return case
    return None

def _tamper_found(data: Dict, record: Dict, check: Dict, check_type: str, checked_by: str, responsible: str):
    """Every failed check: added to the open tamper case (or a new one) + alert to the administrator."""
    case = open_case(record)
    if case is None:
        case = {"case_id": len(record["tamper_cases"]) + 1, "state": "PENDING", "opened_at": _now(),
                "findings": [], "decided_by": None, "decided_at": None, "note": None}
        record["tamper_cases"].append(case)
        _log(record, "TAMPER_CASE_OPENED", checked_by, case_id=case["case_id"])
    case["findings"].append({"check": check_type, "time": _now(), "checked_by": checked_by,
                             "responsible": responsible, "result": check["status"],
                             "localization": _loc_summary(check["localization"])})
    _audit(data, "TAMPER_DETECTED", checked_by, evidence_id=record["evidence_id"],
           check=check_type, result=check["status"], responsible=responsible, case_id=case["case_id"])
    _send(data, _admin_name(data),
          f"TAMPER ALERT ({check_type}, custodian at the time: {responsible}): {_summary(record, check, checked_by)}"
          f" -> your decision is needed: choose \"Review tamper alerts\"")

def decide_tamper(admin: Dict, evidence_id: str, confirm: bool, note: str) -> Dict:
    """Administrator closes the open tamper case: CONFIRM (evidence frozen) or DISMISS (false alarm)."""
    if admin["role"] != "ADMINISTRATOR":
        raise PermissionError("Only the administrator can decide tamper cases.")
    if not note:
        raise ValueError("A reason for the decision is required.")
    data = load_data()
    record = _get_record(data, evidence_id)
    case = open_case(record)
    if case is None:
        raise ValueError("This evidence has no open tamper case.")
    case.update({"state": "CONFIRMED" if confirm else "DISMISSED",
                 "decided_by": admin["username"], "decided_at": _now(), "note": note})
    name = f"{evidence_id} ({record['metadata']['file_name']})"
    if confirm:
        record["status"] = "COMPROMISED"            #frozen: no more transfers or re-verification
        record["custodian"] = record["owner"]
        record["pending_transfer"] = None
        _log(record, "TAMPER_CONFIRMED", admin["username"], case_id=case["case_id"], note=note)
        text = f"Administrator CONFIRMED tampering of {name}. The evidence is now COMPROMISED and frozen. Reason: {note}"
    else:
        _log(record, "TAMPER_DISMISSED", admin["username"], case_id=case["case_id"], note=note)
        text = f"Administrator DISMISSED the tamper alert on {name} (false alarm). Reason: {note}"
    _audit(data, "TAMPER_CONFIRMED" if confirm else "TAMPER_DISMISSED", admin["username"],
           evidence_id=evidence_id, case_id=case["case_id"], note=note)
    for person in {record["owner"]} | {f["responsible"] for f in case["findings"]}:
        _send(data, person, text)
    save_data(data)
    return case

def register_evidence(user: Dict, file_path: str) -> Dict:
    if user["role"] == "ADMINISTRATOR":
        raise PermissionError("The administrator approves transfers and cannot own evidence.")
    file_data = read_file_bytes(file_path)
    fp = fingerprint_bytes(file_data, os.path.basename(file_path))
    evidence_id = sha256_text(fp["roots"]["evidence_root"])[:16]
    data = load_data()
    if evidence_id in data["evidence"]:
        if can_view(user, data["evidence"][evidence_id]):
            raise ValueError(f"This file is already registered with Evidence ID: {evidence_id}")
        raise ValueError("This file is already registered in the system by another user.")
    record = {
        "evidence_id":      evidence_id,
        "owner":            user["username"],   #uploader owns the evidence
        "custodian":        user["username"],   #person currently holding it
        "status":           "WITH_OWNER",
        "upload_time":      _now(),
        "pending_transfer": None,
        "last_check":       None,
        "return_check":     None,
        "tamper_cases":     [],
        "custody_log":      [],
        **fp
    }
    save_original(evidence_id, file_data)          #protected original copy (evidence vault)
    _log(record, "REGISTERED", user["username"])
    data["evidence"][evidence_id] = record
    _audit(data, "EVIDENCE_REGISTERED", user["username"], evidence_id=evidence_id,
           file_name=fp["metadata"]["file_name"])
    save_data(data)
    return record

def request_transfer(user: Dict, evidence_id: str, to_username: str, reason: str, file_path: str) -> Dict:
    data = load_data()
    record = _get_record(data, evidence_id)
    if record["owner"] != user["username"]:
        raise PermissionError(f"Only the owner ({record['owner']}) can transfer this evidence.")
    if record["status"] != "WITH_OWNER":
        raise ValueError(f"Evidence cannot be transferred now. Status: {record['status']}")
    if open_case(record):
        raise ValueError("A tamper case is open for this evidence. The administrator must decide it first.")
    if to_username not in active_users(data):
        raise ValueError(f"No active user named '{to_username}' found.")
    if data["users"][to_username]["role"] == "ADMINISTRATOR":
        raise ValueError("Evidence cannot be transferred to the administrator (they approve transfers).")
    if to_username == user["username"]:
        raise ValueError("You cannot transfer evidence to yourself.")
    if not reason:
        raise ValueError("A reason for the transfer is required.")

    # EXIT CHECK: the file being handed over must match the original,
    # so the receiver can never be blamed for a change made before it left
    check = compare_with_original(file_path, record)
    _log(record, "EXIT_CHECK", user["username"], result=check["status"],
         localization=_loc_summary(check["localization"]))
    if check["status"] != "AUTHENTIC":
        record["last_check"] = {"status": check["status"], "time": _now(), "held_by": record["owner"]}
        _tamper_found(data, record, check, "exit check", user["username"], record["owner"])
        save_data(data)
        check["blocked"] = True
        return check

    record["pending_transfer"] = {"to": to_username, "to_role": data["users"][to_username]["role"],
                                  "reason": reason, "requested_at": _now()}
    record["status"] = "PENDING_APPROVAL"
    _log(record, "TRANSFER_REQUESTED", user["username"], to=to_username, reason=reason)
    save_data(data)
    check["blocked"] = False
    return check

def pending_requests() -> List[Dict]:
    return [r for r in load_data()["evidence"].values() if r["status"] == "PENDING_APPROVAL"]

def decide_transfer(admin: Dict, evidence_id: str, approve: bool) -> Dict:
    if admin["role"] != "ADMINISTRATOR":
        raise PermissionError("Only an administrator can approve transfers.")
    data = load_data()
    record = _get_record(data, evidence_id)
    if record["status"] != "PENDING_APPROVAL":
        raise ValueError("This evidence has no pending transfer request.")
    req = record["pending_transfer"]
    name = f"{evidence_id} ({record['metadata']['file_name']})"
    if approve:
        record["custodian"] = req["to"]
        record["status"] = "WITH_RECEIVER"
        _log(record, "TRANSFER_APPROVED", admin["username"], frm=record["owner"],
             to=req["to"], reason=req["reason"])
        _send(data, record["owner"], f"Your transfer of {name} to {req['to']} was APPROVED.")
        _send(data, req["to"], f"Evidence {name} has been transferred to you by {record['owner']} "
                               f"(reason: {req['reason']}).")
    else:
        record["status"] = "WITH_OWNER"
        _log(record, "TRANSFER_REJECTED", admin["username"], to=req["to"])
        _send(data, record["owner"], f"Your transfer of {name} to {req['to']} was REJECTED by the administrator.")
    record["pending_transfer"] = None
    save_data(data)
    return record

def return_evidence(user: Dict, evidence_id: str, note: str, file_path: str) -> Dict:
    data = load_data()
    record = _get_record(data, evidence_id)
    if record["status"] != "WITH_RECEIVER" or record["custodian"] != user["username"]:
        raise PermissionError("Only the person currently holding this evidence can return it.")

    # RETURN CHECK: the receiver uploads the file they are handing back.
    # The result is recorded but the return is NOT blocked - evidence must
    # always go back to the owner; a mismatch is flagged against the receiver.
    check = compare_with_original(file_path, record)
    note = note or "work completed"
    _log(record, "WORK_COMPLETED_RETURNED", user["username"], to=record["owner"], note=note,
         return_check=check["status"], localization=_loc_summary(check["localization"]))
    record["return_check"] = check["status"]
    record["custodian"] = record["owner"]
    record["status"] = "AWAITING_REVERIFICATION"

    # summary always goes to the owner; if tampered, the administrator is alerted too
    _send(data, record["owner"], f"RETURN SUMMARY: {_summary(record, check, user['username'])} | Work: {note}")
    if check["status"] != "AUTHENTIC":
        _tamper_found(data, record, check, "return check", user["username"], user["username"])
    save_data(data)
    return check

def reverify(user: Dict, evidence_id: str, file_path: str) -> Dict:
    data = load_data()
    record = _get_record(data, evidence_id)
    if record["owner"] != user["username"]:
        raise PermissionError(f"Only the owner ({record['owner']}) can re-verify this evidence.")
    if record["status"] != "AWAITING_REVERIFICATION":
        raise ValueError("Re-verification is done after the evidence has been returned to you. "
                         f"Current status: {record['status']}")

    result = compare_with_original(file_path, record)

    # who is responsible if it changed:
    # receiver's returned file did not match -> the change happened with the receiver;
    # receiver's returned file matched -> it changed after coming back to the owner
    held_by = record["owner"]
    if record["return_check"] != "AUTHENTIC":
        for ev in reversed(record["custody_log"]):
            if ev["event"] == "TRANSFER_APPROVED":
                held_by = ev["to"]
                break

    record["last_check"] = {"status": result["status"], "time": _now(), "held_by": held_by}
    _log(record, "REVERIFIED", user["username"], result=result["status"], held_by=held_by,
         localization=_loc_summary(result["localization"]))
    record["status"] = "WITH_OWNER"
    if result["status"] != "AUTHENTIC":
        _tamper_found(data, record, result, "owner re-verification", user["username"], held_by)
    save_data(data)  #the original Merkle trees are never replaced
    result["held_by"] = held_by
    return result

# STEP 10: AUDIT AND INTEGRITY REPORTING
REPORT_SIGNATURE = "REPORT SIGNATURE (HMAC-SHA256): "

def can_report(user: Dict, r: Dict) -> bool:
    return user["role"] == "ADMINISTRATOR" or r["owner"] == user["username"]

def integrity_checks(record: Dict) -> List[Dict]:
    """Every integrity check in the chain of custody, in order."""
    checks = []
    for ev in record["custody_log"]:
        if ev["event"] == "EXIT_CHECK":
            checks.append({"type": "Exit check", "time": ev["time"], "by": ev["by"],
                           "result": ev["result"], "responsible": ev["by"], "loc": ev.get("localization")})
        elif ev["event"] == "WORK_COMPLETED_RETURNED":
            checks.append({"type": "Return check", "time": ev["time"], "by": ev["by"],
                           "result": ev["return_check"], "responsible": ev["by"], "loc": ev.get("localization")})
        elif ev["event"] == "REVERIFIED":
            checks.append({"type": "Owner re-verification", "time": ev["time"], "by": ev["by"],
                           "result": ev["result"], "responsible": ev["held_by"], "loc": ev.get("localization")})
    return checks

def verdict(record: Dict) -> str:
    checks = integrity_checks(record)
    failed = [c for c in checks if c["result"] != "AUTHENTIC"]
    confirmed = [c for c in record["tamper_cases"] if c["state"] == "CONFIRMED"]
    if confirmed:
        c = confirmed[0]
        who = sorted({f["responsible"] for f in c["findings"]})
        return (f"COMPROMISED - tampering CONFIRMED by administrator {c['decided_by']} on "
                f"{_short_time(c['decided_at'])}. Custodian(s) at the time of the change: {', '.join(who)}. "
                f"Administrator's finding: {c['note']}")
    if open_case(record):
        return "UNDER REVIEW - tampering detected, waiting for the administrator's decision."
    dismissed = [c for c in record["tamper_cases"] if c["state"] == "DISMISSED"]
    if failed and dismissed and checks[-1]["result"] == "AUTHENTIC":
        return (f"INTACT - latest check AUTHENTIC; {len(dismissed)} earlier alert(s) were reviewed "
                f"and dismissed by the administrator as false alarms.")
    if not checks:
        return "NOT YET RE-VERIFIED - only the registration fingerprint exists."
    if not failed:
        return f"INTACT - all {len(checks)} integrity check(s) passed."
    first, last_fail, latest = failed[0], failed[-1], checks[-1]
    return (f"TAMPERING DETECTED - {len(failed)} of {len(checks)} check(s) failed. "
            f"First detected at {first['type'].lower()} on {_short_time(first['time'])} "
            f"(custodian at the time: {first['responsible']}). Most recent failure: {last_fail['type'].lower()} "
            f"(custodian at the time: {last_fail['responsible']}). Latest check result: {latest['result']}.")

