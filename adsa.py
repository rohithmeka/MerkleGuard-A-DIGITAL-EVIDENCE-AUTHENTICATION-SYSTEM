# STEP 6: SECURE STORAGE
# Everything is kept in one JSON file:
#   {"users": {...}, "evidence": {...}, "messages": [...], "audit": [...], "hmac": "..."}
# The "hmac" is a SHA-256 hash of the whole file made with a secret key.
# If anyone edits the file (changes a root, deletes a record, changes their
# role, removes an audit entry), the hmac no longer matches and the program
# refuses to load it. A plain SHA-256 could simply be recomputed by the
# attacker; the HMAC cannot be recomputed without the secret key.
# ============================================================

DATA_VERSION = "merkleguard-3"     #changes whenever the hashing or record format changes
STORE_KEYS = ("version", "users", "evidence", "messages", "audit")

def _empty_store() -> Dict: #The dictionaries hold users and evidence. The lists hold messages and audit entries.
    return {"version": DATA_VERSION, "users": {}, "evidence": {}, "messages": [], "audit": []}

def _get_key() -> bytes: #This function obtains the secret key used by HMAC.
    if os.path.exists(KEY_FILE):
        with open(KEY_FILE, "rb") as f:
            key = f.read()
        if len(key) != 32:
            raise ValueError("Secret key file is damaged. The data file cannot be trusted.")
        return key
    if os.path.exists(DATA_FILE):
        raise ValueError("Secret key is missing. The data file cannot be trusted.")
    os.makedirs(_BASE_DIR, exist_ok=True)
    key = secrets.token_bytes(32)
    with open(KEY_FILE, "wb") as f:
        f.write(key)
    return key

def _sign(content: Dict) -> str:#This function creates an HMAC-SHA256 signature for the application data.
    payload = json.dumps(content, sort_keys=True, separators=(",", ":"))  #canonical form
    return hmac.new(_get_key(), payload.encode("utf-8"), hashlib.sha256).hexdigest()

def load_data() -> Dict: #Whenever the program needs its stored records, this function reads and validates the JSON file.
    if not os.path.exists(DATA_FILE):
        if os.path.exists(KEY_FILE):
            # the key exists, so data was created before -> someone deleted it
            raise ValueError("Data file is missing although the secret key exists (data was deleted). "
                             "To start completely fresh, delete mg_secret.key as well.")
        return _empty_store()
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        try:
            stored = json.load(f)
        except json.JSONDecodeError:
            raise ValueError("Data file is corrupted.")
    if not isinstance(stored, dict):
        raise ValueError("Data file is corrupted.")
    if stored.get("version") != DATA_VERSION:
        raise ValueError("This data file was created by an older version of MerkleGuard (different "
                         "hashing and record format), so it cannot be used. Back up mg_data.json, "
                         "mg_secret.key and the mg_vault folder, then remove them to start fresh.")
    content = {k: stored.get(k, _empty_store()[k]) for k in STORE_KEYS}
    if not hmac.compare_digest(str(stored.get("hmac", "")), _sign(content)):
        raise ValueError("INTEGRITY CHECK FAILED: the data file has been modified outside MerkleGuard.")
    return content

def save_data(content: Dict):#When a user registers an account, registers evidence,
# approves a transfer or completes another operation, the modified data eventually goes through save_data().
    content = {k: content.get(k, _empty_store()[k]) for k in STORE_KEYS}
    content["version"] = DATA_VERSION
    stored = {**content, "hmac": _sign(content)}
    os.makedirs(_BASE_DIR, exist_ok=True)
    tmp = DATA_FILE + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:   #write to a temp file first...
        json.dump(stored, f, indent=4)
    os.replace(tmp, DATA_FILE)                    #...then swap, so a crash never leaves half a file

