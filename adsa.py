def _suite_data(kind: str, size: int) -> bytes:
    rng = random.Random(7)
    words = ["evidence", "report", "the", "case", "witness", "officer", "statement", "on", "at", "a"]
    text = " ".join(rng.choice(words) for _ in range(size // 4)).encode()[:size]
    if kind == "Plain text":
        return text
    if kind == "Compressed (zip-like)":
        out, i = b"", 0
        while len(out) < size:                              #compressed data is high-entropy
            out += zlib.compress(text[i % len(text):] + bytes([i % 256]))
            i += 1
        return out[:size]
    if kind == "Random binary (encrypted-like)":
        return bytes(rng.getrandbits(8) for _ in range(size))
    if kind == "Repetitive binary (log/blank)":
        return (b"\x00" * 900 + b"LOG ENTRY OK\n" * 8) * (size // 1004 + 1)
    # mixed document: text + embedded image-like block + text
    third = size // 3
    return text[:third] + bytes(rng.getrandbits(8) for _ in range(third)) + text[:size - 2 * third]

